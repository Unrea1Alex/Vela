"""C11 backend. Explicit temporaries preserve Vela's left-to-right evaluation.

No user-controlled spelling becomes raw C: identifiers are prefixed, string bytes
are escaped, and all operators/types have already been checked.
"""
from importlib.resources import files

from .. import ir
from ..source import Source, Span
from ..typesys import BOOL, INT, STRING, UNIT, INT_LIST, STRING_LIST, Type


def c_bytes(value: str) -> str:
    # Three-digit octal escapes cannot absorb subsequent digits (unlike hex).
    data = value.encode("utf-8")
    return " ".join('"' + "".join(f"\\{byte:03o}" for byte in data[i:i + 512]) + '"'
                    for i in range(0, len(data), 512)) or '""'


def c_type(type_: Type) -> str:
    return {INT: "int64_t", BOOL: "int", STRING: "v_string", UNIT: "uint8_t",
            INT_LIST: "v_int_list*", STRING_LIST: "v_string_list*"}.get(type_, "v_e_" + type_.name)


def local(binding: ir.Binding) -> str:
    return f"v_l_{binding.id}"


class CEmitter:
    def __init__(self, source: Source):
        self.source = source
        self.lines: list[str] = []
        self.depth, self.next_temp = 0, 0
        self.function: ir.Function | None = None

    def line(self, text: str = "") -> None:
        self.lines.append("    " * self.depth + text)

    def location(self, span: Span) -> str:
        line, column = self.source.position(span.start)
        return f"{c_bytes(self.source.name)}, {line}, {column}"

    def temporary(self, type_: Type, value: str | None = None) -> str:
        self.next_temp += 1
        name = f"v_t_{self.next_temp}"
        self.line(f"{c_type(type_)} {name}" + (f" = {value}" if value is not None else "") + ";")
        return name

    def signature(self, fn: ir.Function) -> str:
        params = ", ".join(f"{c_type(p.type)} {local(p)}" for p in fn.parameters) or "void"
        return f"static {c_type(fn.signature.returns)} v_f_{fn.signature.name}({params})"

    def emit(self, program: ir.Program) -> str:
        self.line("/* Generated by Vela 0.2.0. Do not edit; edit the .vela source. */")
        self.lines.append(files("vela.backends").joinpath("runtime.h").read_text(encoding="utf-8"))
        for enum in program.enums:
            self.line("typedef struct {")
            self.depth += 1
            self.line("int tag;")
            self.line("union {")
            self.depth += 1
            for variant in enum.variants:
                self.line("struct {")
                self.depth += 1
                if not variant.fields:
                    self.line("uint8_t empty;")
                for index, type_ in enumerate(variant.fields):
                    self.line(f"{c_type(type_)} f{index};")
                self.depth -= 1
                self.line(f"}} k{variant.tag};")
            self.depth -= 1
            self.line("} data;")
            self.depth -= 1
            self.line(f"}} {c_type(enum.type)};")
        self.line("static v_e_IntResult v_result(v_parse_result parsed) {")
        self.line("    v_e_IntResult result = {0};")
        self.line("    result.tag = parsed.ok ? 0 : 1;")
        self.line("    if (parsed.ok) result.data.k0.f0 = parsed.value;")
        self.line("    else result.data.k1.f0 = parsed.error;")
        self.line("    return result;")
        self.line("}")
        self.line("static v_e_StringResult v_string_result(v_io_result parsed) {")
        self.line("    v_e_StringResult result = {0}; result.tag = parsed.ok ? 0 : 1;")
        self.line("    if (parsed.ok) result.data.k0.f0 = parsed.value;")
        self.line("    else result.data.k1.f0 = parsed.value; return result;")
        self.line("}")
        self.line("static v_e_WriteResult v_write_result(v_io_result parsed) {")
        self.line("    v_e_WriteResult result = {0}; result.tag = parsed.ok ? 0 : 1;")
        self.line("    if (!parsed.ok) result.data.k1.f0 = parsed.value; return result;")
        self.line("}")
        for fn in program.functions:
            self.line(self.signature(fn) + ";")
        for fn in program.functions:
            self.function = fn
            self.line(self.signature(fn) + " {")
            self.depth += 1
            for condition in fn.requires:
                self.contract(condition, "precondition")
            self.block(fn.body)
            # Checked IR guarantees returns, but C compilers need a default path
            # following a switch. This guard also detects corrupted enum tags.
            self.line(f'v_panic({self.location(fn.span)}, "unreachable function end");')
            self.line(f"return {local_zero(fn.signature.returns)};")
            self.depth -= 1
            self.line("}")
        main = next(fn for fn in program.functions if fn.signature.name == "main")
        self.line("int main(int argc, char **argv) {")
        self.line("    v_argc = argc; v_argv = argv;")
        self.line("    v_runtime_init();")
        self.line("    int code = 0;")
        if main.signature.returns == INT:
            self.line(f"    code = v_exit_code(v_f_main(), {self.location(main.span)});")
        else:
            self.line("    (void)v_f_main();")
        self.line(f'    if (fflush(stdout) == EOF) v_panic({self.location(main.span)}, "failed to flush standard output");')
        self.line("    return code;")
        self.line("}")
        return "\n".join(self.lines) + "\n"

    def expression(self, expr: ir.Expr) -> str:
        if isinstance(expr, ir.Constant):
            if expr.type == INT:
                value = "INT64_MIN" if expr.value == -9223372036854775808 else (
                    f"(-INT64_C({-expr.value}))" if expr.value < 0 else f"INT64_C({expr.value})")
            elif expr.type == BOOL:
                value = "1" if expr.value else "0"
            elif expr.type == STRING:
                value = f"v_text({c_bytes(expr.value)}, {len(expr.value.encode('utf-8'))})"
            else:
                value = "0"
            return self.temporary(expr.type, value)
        if isinstance(expr, ir.Local):
            # Snapshot even locals: later argument evaluation may have effects.
            return self.temporary(expr.type, local(expr.binding))
        if isinstance(expr, ir.Unary):
            value = self.expression(expr.operand)
            code = f"v_neg({value}, {self.location(expr.span)})" if expr.op == "-" else f"(!{value})"
            return self.temporary(expr.type, code)
        if isinstance(expr, ir.Binary):
            left = self.expression(expr.left)
            if expr.op in {"&&", "||"}:
                result = self.temporary(BOOL, left)
                condition = result if expr.op == "&&" else "!" + result
                self.line(f"if ({condition}) {{")
                self.depth += 1
                right = self.expression(expr.right)
                self.line(f"{result} = {right};")
                self.depth -= 1
                self.line("}")
                return result
            right = self.expression(expr.right)
            arithmetic = {"+": "add", "-": "sub", "*": "mul", "/": "div", "%": "rem"}
            if expr.op in arithmetic:
                value = f"v_{arithmetic[expr.op]}({left}, {right}, {self.location(expr.span)})"
            elif expr.left.type == STRING:
                value = f"v_string_eq({left}, {right})"
                if expr.op == "!=":
                    value = "!" + value
            else:
                value = f"({left} {expr.op} {right})"
            return self.temporary(expr.type, value)
        if isinstance(expr, ir.Call):
            args = [self.expression(arg) for arg in expr.args]
            if expr.target.builtin:
                name = expr.target.name
                abi = expr.target.abi
                if abi == "print":
                    code = f"v_print_{expr.args[0].type.name}({args[0]}, {self.location(expr.span)})"
                elif abi == "plain":
                    code = f"v_{name}({', '.join(args)})"
                elif abi == "int_result":
                    code = f"v_result(v_{name}({', '.join(args)}))"
                else:
                    code = f"v_{name}({', '.join(args + [self.location(expr.span)])})"
                    if abi == "string_result":
                        code = f"v_string_result({code})"
                    elif abi == "write_result":
                        code = f"v_write_result({code})"
            else:
                code = f"v_f_{expr.target.name}({', '.join(args)})"
            return self.temporary(expr.type, code)
        if isinstance(expr, ir.Construct):
            args = [self.expression(arg) for arg in expr.args]
            result = self.temporary(expr.type, "{0}")
            self.line(f"{result}.tag = {expr.variant.tag};")
            for index, arg in enumerate(args):
                self.line(f"{result}.data.k{expr.variant.tag}.f{index} = {arg};")
            return result
        raise AssertionError(f"Unhandled IR expression: {type(expr)}")

    def contract(self, condition: ir.Expr, kind: str) -> None:
        value = self.expression(condition)
        expression_text = self.source.text[condition.span.start:condition.span.end]
        self.line(f"if (!{value}) v_panic({self.location(condition.span)}, {c_bytes(kind + ' failed: ' + expression_text)});")

    def block(self, body: tuple[ir.Stmt, ...]) -> None:
        for stmt in body:
            self.statement(stmt)

    def statement(self, stmt: ir.Stmt) -> None:
        if isinstance(stmt, ir.Bind):
            value = self.expression(stmt.value)
            self.line(f"{c_type(stmt.binding.type)} {local(stmt.binding)} = {value};")
        elif isinstance(stmt, ir.Assign):
            value = self.expression(stmt.value)
            self.line(f"{local(stmt.binding)} = {value};")
        elif isinstance(stmt, ir.Expression):
            self.line(f"(void){self.expression(stmt.value)};")
        elif isinstance(stmt, ir.Return):
            self.line("{")
            self.depth += 1
            value = self.expression(stmt.value)
            assert self.function is not None
            result = local(self.function.result)
            self.line(f"{c_type(stmt.value.type)} {result} = {value};")
            for condition in self.function.ensures:
                self.contract(condition, "postcondition")
            self.line(f"return {result};")
            self.depth -= 1
            self.line("}")
        elif isinstance(stmt, ir.If):
            condition = self.expression(stmt.condition)
            self.line(f"if ({condition}) {{")
            self.depth += 1
            self.block(stmt.then_body)
            self.depth -= 1
            if stmt.else_body:
                self.line("} else {")
                self.depth += 1
                self.block(stmt.else_body)
                self.depth -= 1
            self.line("}")
        elif isinstance(stmt, ir.While):
            self.line("for (;;) {")
            self.depth += 1
            condition = self.expression(stmt.condition)
            self.line(f"if (!{condition}) break;")
            self.block(stmt.body)
            self.depth -= 1
            self.line("}")
        elif isinstance(stmt, ir.Match):
            value = self.expression(stmt.value)
            self.line(f"switch ({value}.tag) {{")
            self.depth += 1
            for arm in stmt.arms:
                self.line(f"case {arm.variant.tag}: {{")
                self.depth += 1
                for index, binding in enumerate(arm.bindings):
                    if binding is not None:
                        self.line(f"{c_type(binding.type)} {local(binding)} = {value}.data.k{arm.variant.tag}.f{index};")
                self.block(arm.body)
                self.line("break;")
                self.depth -= 1
                self.line("}")
            self.line(f'default: v_panic({self.location(stmt.span)}, "invalid enum tag");')
            self.depth -= 1
            self.line("}")
        else:
            raise AssertionError(f"Unhandled IR statement: {type(stmt)}")


def local_zero(type_: Type) -> str:
    if type_ == STRING:
        return 'v_text("", 0)'
    if type_ in {INT, BOOL, UNIT, INT_LIST, STRING_LIST}:
        return "0"
    # C11 compound literal, also supported by MSVC in /std:c11 mode.
    return f"({c_type(type_)}){{0}}"


def emit_c(program: ir.Program, source: Source) -> str:
    return CEmitter(source).emit(program)

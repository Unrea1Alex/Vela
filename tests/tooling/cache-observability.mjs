import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import fs from 'node:fs/promises';
import path from 'node:path';
const [compiler,output] = process.argv.slice(2).map(p=>path.resolve(p));
const run = promisify(execFile);
const base = await fs.mkdtemp(path.join(output,'cache-report-'));
const source = path.join(base,'main.vela'), cache = path.join(base,'cache');
await fs.writeFile(source,'fn main() -> Int { return 7; }\n');
const checks=[];
async function invoke(args) {
  const r=await run(compiler,args,{windowsHide:true,maxBuffer:32*1024*1024});
  return {...r,events:r.stderr.trim().split(/\r?\n/).filter(Boolean).map(line=>JSON.parse(line))};
}
const args=['check',source,'--json','--cache',cache,'--cache-report'];
const cold=await invoke(args),warm=await invoke(args);
assert.equal(JSON.parse(cold.stdout).ok,true);
assert.equal(cold.stdout,warm.stdout);
assert.ok(cold.events.some(x=>x.layer==='check-v1'&&x.status==='miss'));
assert.ok(warm.events.some(x=>x.layer==='check-v1'&&x.status==='hit'));
assert.ok(cold.events.some(x=>x.phase==='directory'&&x.status==='ready'));
assert.ok((await fs.stat(cache)).isDirectory());
checks.push('auto-created directory, cold miss, warm hit and JSON stdout parity');
const hit=warm.events.find(x=>x.layer==='check-v1'&&x.status==='hit');
const record=path.join(cache,'vela-cache-v1-'+hit.key);
await fs.writeFile(record,'broken');
assert.ok((await invoke(args)).events.some(x=>x.layer==='check-v1'&&x.reason==='corrupt'));
checks.push('corrupt record is a visible miss and is repaired');
await fs.unlink(record); await fs.mkdir(record);
const failed=await invoke(args.filter(x=>x!=='--cache-report'));
assert.equal(JSON.parse(failed.stdout).ok,true);
assert.ok(failed.events.some(x=>x.phase==='write'&&x.status==='failed'&&x.reason==='write_error'));
checks.push('failed atomic publication warns without report flag and preserves success');
assert.ok((await fs.readdir(cache)).every(x=>x.startsWith('vela-cache-v1-')));
checks.push('failed publication removes private temporary files');
const unavailable=await invoke(['check',source,'--cache',source]);
assert.ok(unavailable.events.some(x=>x.status==='unavailable'));
assert.equal(await fs.readFile(source,'utf8'),'fn main() -> Int { return 7; }\n');
checks.push('file as cache directory warns and falls back without touching source');
const missingParent=await invoke(['check',source,'--cache',path.join(base,'absent','nested'),'--cache-report']);
assert.ok(missingParent.events.some(x=>x.status==='unavailable'));
checks.push('missing parent is not silently created recursively');
const off=await invoke(['check',source,'--cache-report']);
assert.equal(off.events.length,1); assert.equal(off.events[0].status,'disabled');
checks.push('explicit disabled diagnostic');
const emit=['emit-c',source,'--cache',cache,'--cache-report'];
const c1=await invoke(emit),c2=await invoke(emit),plain=await invoke(['emit-c',source]);
assert.equal(c1.stdout,c2.stdout); assert.equal(c2.stdout,plain.stdout);
assert.ok(c2.events.some(x=>x.layer==='c-v1'&&x.status==='hit'));
await fs.writeFile(source,'fn main() -> Int { return 8; }\n');
const changed=await invoke(emit);
assert.notEqual(changed.stdout,plain.stdout);
assert.ok(changed.events.some(x=>x.layer==='c-v1'&&x.status==='miss'));
checks.push('C stdout parity and source-change invalidation');
await assert.rejects(run(compiler,['check',source,'--cache'],{windowsHide:true}),e=>e.code===2&&/requires a directory/.test(e.stderr));
checks.push('missing cache argument rejects without panic');
const evidence={schema_version:1,checks,passed:checks.length,failed:0};
await fs.writeFile(path.join(output,'cache-observability.json'),JSON.stringify(evidence,null,2)+'\n');
console.log(JSON.stringify(evidence,null,2));

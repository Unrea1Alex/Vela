import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
const root=path.resolve(process.argv[2]??'.'),exe=path.join(root,'bin/vela-api.exe');
const index=path.join(root,'docs/api-index.json'),purpose=path.join(root,'docs/api-purpose.json');
const work=await fs.mkdtemp(path.join(os.tmpdir(),'vela-api12-')),checks=[];
const call=({query='',mode='query',offset=0,limit=3,budget=8192,version='',fingerprint='',file=index,metadata=purpose}={})=>{
 const run=spawnSync(exe,[file,metadata,query,mode,String(offset),String(limit),String(budget),version,fingerprint],{encoding:'utf8',windowsHide:true});
 assert.ok(run.status===0||run.status===2,run.stderr);return JSON.parse(run.stdout);
};
const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
try{
 const exact=call({query:'std/directory:walk',mode:'name'});
 check('exact ID',exact.ok&&exact.state==='matches'&&exact.total===1&&exact.items[0].id==='std/directory:walk');
 check('checked signature',exact.items[0].signature==='fn walk(root:path::Path,limits:Limits)->Result<List<WalkEntry>,Error> effects {io,state}');
 check('metadata fields',exact.items[0].ownership&&exact.items[0].limits&&exact.items[0].example&&exact.items[0].recipe==='directory');
 const raw=await fs.readFile(index),meta=await fs.readFile(purpose);
 const fingerprint=crypto.createHash('sha256').update(raw).update('\n').update(meta).digest('hex');
 check('independent fingerprint',exact.fingerprint===fingerprint);
 check('JSON lookup',call({query:'std/json_stream:skip_value',mode:'name'}).items[0].signature.startsWith('fn skip_value('));
 check('HTTP lookup',call({query:'std/http:curl_transfer',mode:'name'}).items[0].limits.includes('exact transfer timeout'));
 check('Unicode purpose',call({query:'каталог'}).total>=6);
 check('ASCII folded purpose',call({query:'DIRECTORY METADATA'}).total===call({query:'directory metadata'}).total);
 check('unknown name',call({query:'not_a_real_symbol',mode:'name'}).state==='not_found');
 check('no matches',call({query:'not_a_real_purpose'}).state==='no_matches');
 check('empty query',call().state==='empty'&&call({query:' \t\r\n'}).total===0);
 check('ambiguous exact name',call({query:'open',mode:'name'}).state==='ambiguous');
 check('case sensitive exact name',call({query:'std/directory:Walk',mode:'name'}).state==='not_found');
 check('stale version',call({version:'0.0.0'}).reason==='stale_version');
 check('stale fingerprint',call({fingerprint:'0'.repeat(64)}).reason==='stale_fingerprint');
 let offset=0,ids=[],total=0;
 do{const page=call({query:'directory',offset,limit:2,fingerprint});total=page.total;ids.push(...page.items.map(x=>x.id));offset=page.next_offset;}while(offset!==null);
 check('pages cover exactly once',new Set(ids).size===ids.length&&ids.length===total);
 check('byte order',ids.every((id,i)=>i===0||Buffer.compare(Buffer.from(ids[i-1]),Buffer.from(id))<0));
 check('out of range page',call({query:'directory',offset:4000}).items.length===0);
 check('payload limit',call({query:'std/directory:walk',mode:'name',budget:128}).reason==='response_limit');
 check('invalid argument',call({offset:-1}).reason==='invalid_input');
 const document=JSON.parse(raw),mutated=path.join(work,'catalog.json');
 document.modules[0].api.items.push(document.modules[0].api.items[0]);await fs.writeFile(mutated,JSON.stringify(document));
 check('duplicate IDs fail even empty search',call({file:mutated}).reason==='duplicate_id');
 await fs.writeFile(mutated,'{');check('malformed JSON',call({file:mutated}).reason==='invalid_catalog');
 const bad=JSON.parse(raw);bad.modules[0].api.items[0].signature=42;await fs.writeFile(mutated,JSON.stringify(bad));
 check('malformed field',call({file:mutated}).reason==='invalid_catalog');
 await fs.writeFile(mutated,' '.repeat(1048577));check('catalog byte bound',call({file:mutated}).reason==='catalog_limit');
 const unicode={modules:[{module:'unicode',api:{version:exact.version,items:['\uE000','😀'].map(name=>({name,kind:'function',signature:'fn example()->Int',effects:[]}))}}]};
 const policy={modules:[{module:'unicode',purpose:'unicode sort',ownership:'value',limits:'bounded',example:'42',recipe:'basics'}]};
 await fs.writeFile(mutated,JSON.stringify(unicode));const policyFile=path.join(work,'purpose.json');await fs.writeFile(policyFile,JSON.stringify(policy));
 const ordered=call({file:mutated,metadata:policyFile,query:'unicode'}).items.map(x=>x.id);
 check('UTF8 rather than UTF16 order',ordered[0]==='unicode:\uE000'&&ordered[1]==='unicode:😀');
 console.log(JSON.stringify({schema_version:1,passed:checks.length,checks}));
}finally{await fs.rm(work,{recursive:true,force:true});}
